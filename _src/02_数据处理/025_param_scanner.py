# ---- 模式常量 ----
模式_单个 = "单个参数"
模式_任一 = "任一参数(A或B)"
模式_全部 = "全部参数(A和B)"
模式_所有 = "所有参数"
模式_字段及值 = "参数字段及参数对应字段值"
全部模式列表: List[str] = [模式_单个, 模式_任一, 模式_全部, 模式_所有, 模式_字段及值]

# 空白拆分（连续空白视为一个分隔符）
_空白拆分 = re.compile(r"\s+")


# ---- 1) 扫描参数 ----
def 扫描参数(数据集对象, 列引用: str) -> List[str]:
    """
    扫描 源列 单元格的"奇数位 token"，去重后作为参数候选返回。

    :param 数据集对象: 已加载的 数据集 实例
    :param 列引用: 列名 或 Excel 列字母
    :return: 排序后的参数名列表（去重）
    :raises ValueError: 列引用解析失败
    """
    if 数据集对象 is None:
        return []
    df = 数据集对象.数据框
    源列真名 = 解析列引用(列引用, df)

    参数集合: set[str] = set()
    # 向量化 → 转 list 再循环，比逐行 .iloc 快
    源序列 = _安全取列(df, 源列真名).astype("object").tolist()
    for 值 in 源序列:
        token列表 = _拆分单元格(值)
        # 奇数位 = 索引 0, 2, 4, ...
        for i in range(0, len(token列表), 2):
            参数 = token列表[i]
            if 参数:
                参数集合.add(参数)
    结果 = sorted(参数集合)
    debug_print(f"扫描参数完成：列={源列真名} | 行数={len(源序列)} | 参数={len(结果)}")
    return 结果


# ---- 2) 按参数提取 ----
def 按参数提取(数据集对象,
          源列: str,
          参数列表: Sequence[str],
          模式: str = 模式_单个,
          合并分隔符: str = ",",
          键值连接符: str = "=",
          键值对分隔符: str = ";",
          覆盖同名列: bool = False,
          目标列名: Optional[str] = None,
          输出对应值: bool = False) -> "数据集":
    """
    在数据集中追加一列，存放从 源列 单元格按“奇数位=参数名/偶数位=参数值”规则提取的结果。

    :param 数据集对象: 数据集实例
    :param 源列: 源列引用
    :param 参数列表: 用户选择的参数名（模式_所有 时可忽略）
    :param 模式: 取自 全部模式列表
    :param 合并分隔符: "全部" 模式下多值拼接分隔符
    :param 键值连接符: "所有" 模式下 K-V 之间的连接符
    :param 键值对分隔符: "所有" 模式下相邻 K=V 之间的分隔符
    :param 覆盖同名列: True 时，若 目标列名 已存在则直接覆盖；False 时且目标列已存在，
                     则在目标列前插入名为 "{目标}_提取参数" 的新列
    :param 目标列名: 新列名；None=自动生成
    :return: 新数据集
    :raises ValueError: 列不存在 / 模式非法 / 参数列表非法
    """
    if 模式 not in 全部模式列表:
        记录错误(f"按参数提取：未知模式 {模式}")
        raise ValueError(f"未知模式：{模式}")
    if 模式 in (模式_单个, 模式_任一, 模式_全部) and not 参数列表:
        raise ValueError("当前模式需要至少选择一个参数")

    df = 数据集对象.数据框.copy()
    源列真名 = 解析列引用(源列, df)

    # 模式_所有 走多列扩展分支（每参数一列 + 2 空列间隔），其它参数（目标列名/覆盖同名列等）忽略
    if 模式 == 模式_所有:
        return _展开所有参数列(数据集对象, df, 源列真名, 参数列表)

    # 模式_字段及值：参数名列（+5 列） + 可选的对应值列（+6 起），独立扩展行数
    if 模式 == 模式_字段及值:
        return _展开参数字段及值(数据集对象, df, 源列真名, 参数列表, bool(输出对应值))

    解析后目标, 是列字母 = 解析目标列名(目标列名, df)
    期望列名 = 解析后目标 or _默认列名(源列真名, 模式, 参数列表)

    # 选模式对应的提取函数
    if 模式 == 模式_单个:
        目标参数 = 参数列表[0]
        def 提取(值): return _取单参数值(_拆分单元格(值), 目标参数)
    elif 模式 == 模式_任一:
        目标集 = list(参数列表)
        def 提取(值): return _取任一参数值(_拆分单元格(值), 目标集)
    else:  # 模式_全部
        目标集 = list(参数列表)
        def 提取(值): return _取全部参数值(_拆分单元格(值), 目标集, 合并分隔符)

    源序列 = _安全取列(df, 源列真名)
    结果序列 = 源序列.astype("object").map(提取)

    # 目标列处理：
    #   - 显式勾选覆盖 → 直接覆盖目标列
    #   - 目标列已存在但未勾选覆盖 → 在目标列前插入 "{目标}_提取参数"
    #   - 其它 → 使用 期望列名，冲突时自动追加 _2/_3
    if 解析后目标 and 解析后目标 in df.columns and not 覆盖同名列:
        插入位置 = list(df.columns).index(解析后目标)
        新列名 = _生成不冲突列名(df, f"{解析后目标}_提取参数")
        df.insert(插入位置, 新列名, 结果序列)
    else:
        if 解析后目标 and 覆盖同名列:
            新列名 = 期望列名
        else:
            新列名 = _生成不冲突列名(df, 期望列名)
        df[新列名] = 结果序列

    debug_print(f"按参数提取完成：列={源列真名} → {新列名} | 模式={模式} | 参数={list(参数列表)}")
    return _复制数据集(数据集对象, df)


# ---- 2.5) 模式_所有：多列扩展 ----
def _展开所有参数列(原数据集, df: pd.DataFrame, 源列真名: str,
             参数列表: Sequence[str]) -> "数据集":
    """
    模式_所有 专用：每个选中参数独立成一列，从 原最大列+3 开始（保留 2 空列间隔）。

    规则：
        1) 未选参数（参数列表 为空） → 调 扫描参数() 取全部
        2) df 末尾先追加 2 个空列做视觉间隔（Excel 表头显示空白）
        3) 再依次追加每个参数列，单元格值 = 该行 K=V 字典对应值；缺失=空串
        4) 列名同名冲突 → 自动追加 _2/_3 防覆盖
    """
    # 1) 参数集合：未选 → 全部扫描
    if 参数列表:
        参数列 = [p for p in 参数列表 if p]
    else:
        参数列 = 扫描参数(原数据集, 源列真名)
    if not 参数列:
        debug_print("按参数提取(所有)：未发现任何参数，跳过追加")
        return _复制数据集(原数据集, df)

    # 2) 一次性把每行解析为 {K: V} 字典
    源序列 = _安全取列(df, 源列真名).astype("object").tolist()
    每行字典 = [_解析为字典(_拆分单元格(值)) for 值 in 源序列]

    # 3) 末尾追加 2 个空列（标题为不同长度空白，避免 pandas 重复列名歧义）
    df.insert(len(df.columns), " ", "", allow_duplicates=True)
    df.insert(len(df.columns), "  ", "", allow_duplicates=True)

    # 4) 每个参数追加一列；同名冲突 → _2/_3
    for 参 in 参数列:
        新名 = _生成不冲突列名(df, 参)
        df[新名] = [字典.get(参, "") for 字典 in 每行字典]

    debug_print(f"按参数提取(所有)：列={源列真名} | 参数={参数列} | 新增列数={len(参数列)}（前置 2 空列间隔）")
    return _复制数据集(原数据集, df)


# ---- 2.6) 模式_字段及值：参数名列（+5 列）+ 可选对应值列（+6 起） ----
def _展开参数字段及值(原数据集, df: pd.DataFrame, 源列真名: str,
              参数列表: Sequence[str], 输出对应值: bool) -> "数据集":
    """
    模式_字段及值 专用：

    1) 参数名列：去重后写到 原最大列+5 处（前 4 列空白做间隔），从第 1 行起逐行输出。
    2) 输出对应值=True 时，从 原最大列+6 起，每个参数独立成列；
       列内逐行写出该参数 所有去重后的 对应值。
    3) 参数列表 为空 或 等于候选集 时，默认全部参数（即未选/全选 → 默认所有）。

    注意：本模式输出的"参数列"与"值列"的行数通常与 df 原行数不同，
        需要把 df 的行数扩展到 max(原行数, 参数数, 各值列最大去重值数)；
        被扩展出来的"原列空行"留空（NaN/""）。
    """
    # 1) 计算候选集，处理"全选/全不选 → 默认所有"
    候选集 = 扫描参数(原数据集, 源列真名)
    候选集合 = set(候选集)
    用户参数 = [p for p in (参数列表 or []) if p]
    用户去重 = list(dict.fromkeys(用户参数))    # 保持顺序去重
    if (not 用户去重) or (set(用户去重) >= 候选集合 and 候选集合):
        参数列 = 候选集                                          # 默认所有 = 字典序候选集
    else:
        参数列 = 用户去重
    if not 参数列:
        debug_print("按参数提取(字段及值)：未发现任何参数，跳过追加")
        return _复制数据集(原数据集, df)

    # 2) 解析每行字典；若需要值列，按参数收集"去重后对应值列表"
    源序列 = _安全取列(df, 源列真名).astype("object").tolist()
    每行字典 = [_解析为字典(_拆分单元格(值)) for 值 in 源序列]
    参数到去重值: Dict[str, List[str]] = {}
    if 输出对应值:
        for 参 in 参数列:
            收集: List[str] = []
            已见: set[str] = set()
            for 字典 in 每行字典:
                v = 字典.get(参)
                if v is None:
                    continue
                文本 = str(v)
                if 文本 == "" or 文本 in 已见:
                    continue
                已见.add(文本)
                收集.append(文本)
            参数到去重值[参] = 收集

    # 3) 计算需要的总行数：max(原行数, 参数数, 各值列最大长度)
    原行数 = len(df)
    最大值列长度 = max((len(v) for v in 参数到去重值.values()), default=0)
    需要行数 = max(原行数, len(参数列), 最大值列长度)
    if 需要行数 > 原行数:                                       # 扩展 df 行数，新增行所有原列留空
        追加 = pd.DataFrame({列: [""] * (需要行数 - 原行数) for 列 in df.columns})
        df = pd.concat([df, 追加], ignore_index=True)

    # 4) 前置 4 个空列做间隔（标题用不同长度空白避免重复列名）
    for i in range(4):
        df.insert(len(df.columns), " " * (i + 1), "", allow_duplicates=True)

    # 5) 参数名列：原最大列+5
    参数列名 = _生成不冲突列名(df, "参数字段")
    参数列填充 = list(参数列) + [""] * (需要行数 - len(参数列))
    df[参数列名] = 参数列填充

    # 6) 输出对应值=True：从 +6 起每参数一列
    if 输出对应值:
        for 参 in 参数列:
            新名 = _生成不冲突列名(df, f"{参}_值")
            值列表 = 参数到去重值.get(参, [])
            df[新名] = 值列表 + [""] * (需要行数 - len(值列表))

    debug_print(
        f"按参数提取(字段及值)：列={源列真名} | 参数数={len(参数列)} | "
        f"输出对应值={输出对应值} | 行扩展={需要行数 - 原行数}"
    )
    return _复制数据集(原数据集, df)


# ---- 3) 内部工具 ----
def _拆分单元格(值) -> List[str]:
    """单元格 → 空白拆分后的 token 列表（None / NaN → 空列表）。"""
    if 值 is None:
        return []
    try:
        if pd.isna(值):
            return []
    except Exception:
        pass
    文本 = str(值).strip()
    if not 文本:
        return []
    return _空白拆分.split(文本)


def _解析为字典(token列表: List[str]) -> Dict[str, str]:
    """奇数位作 key，偶数位作 value；尾部落单则忽略。"""
    字典: Dict[str, str] = {}
    for i in range(0, len(token列表) - 1, 2):
        键 = token列表[i]
        值 = token列表[i + 1]
        if 键:
            字典[键] = 值
    return 字典


def _取单参数值(token列表: List[str], 参数名: str) -> str:
    """取指定参数后紧跟的一个 token，找不到返回空串。"""
    for i in range(0, len(token列表) - 1, 2):
        if token列表[i] == 参数名:
            return token列表[i + 1] or ""
    return ""


def _取任一参数值(token列表: List[str], 参数列表: Sequence[str]) -> str:
    """
    命中 参数列表 中任一参数即输出；多个命中时按 K:V 拼接。

    规则：
        - 多个参数都命中 → "FMA:1377,FMB:1336"
        - 仅一个命中 → "FMA:1377"
        - 无命中 → ""
    """
    字典 = _解析为字典(token列表)
    片段: List[str] = []
    for 参数 in 参数列表:
        if 参数 in 字典:
            片段.append(f"{参数}:{字典[参数]}")
    if not 片段:
        return ""
    return ",".join(片段)


def _取全部参数值(token列表: List[str], 参数列表: Sequence[str], 分隔符: str) -> str:
    """
    按参数列表顺序输出 K:值，缺失的参数输出 K:空值。

    规则：
        - 全部命中 → "FMA:1377\nFMB:1336"
        - 部分命中 → "FMA:1377\nFMB:空值"
        - 全部缺失 → "FMA:空值\nFMB:空值"
    """
    字典 = _解析为字典(token列表)
    片段: List[str] = []
    for 参数 in 参数列表:
        值 = 字典.get(参数, "空值")
        片段.append(f"{参数}:{值}")
    return "\n".join(片段)


# ---- 4) 默认列名 / 防冲突 / 复制数据集 ----
def _默认列名(源列: str, 模式: str, 参数列表: Sequence[str]) -> str:
    """根据模式与参数生成可读的默认列名（仅用于单列输出模式）。"""
    if 模式 == 模式_单个:
        return f"{源列}_{参数列表[0]}"
    标签 = "_".join(参数列表)
    后缀 = "或" if 模式 == 模式_任一 else "和"
    return f"{源列}_{标签}_{后缀}"


def _生成不冲突列名(数据框: pd.DataFrame, 期望列名: str) -> str:
    """期望列名已存在则追加 _2/_3 直到不冲突。"""
    if 期望列名 not in 数据框.columns:
        return 期望列名
    序号 = 2
    while True:
        新名 = f"{期望列名}_{序号}"
        if 新名 not in 数据框.columns:
            return 新名
        序号 += 1


def _复制数据集(原数据集, 新数据框: pd.DataFrame) -> "数据集":
    """基于原数据集来源信息构造新的 数据集 实例。"""
    return 数据集(数据框=新数据框,
               来源类型=原数据集.来源类型,
               来源路径=原数据集.来源路径,
               工作簿名=原数据集.工作簿名,
               工作表名=原数据集.工作表名,
               表头行号=原数据集.表头行号)
