# ============================================================
# 025_param_scanner.py
# 功能：物料号长参数表 - 参数扫描与按参数提取
#   1) 扫描参数(数据集对象, 列引用)
#      1.1) 遍历 源列 每个单元格
#      1.2) 按空白拆分 → 取奇数位 token（索引 0,2,4...）作为参数名
#      1.3) set 去重 + 字典序排序返回
#   2) 按参数提取(数据集, 源列, 参数列表, 模式, ...)
#      2.1) 模式=单个    → 取首个参数对应的值
#      2.2) 模式=任一    → 命中参数列表中任一即输出其值
#      2.3) 模式=全部    → 必须全命中，按 合并分隔符 拼值（顺序按 参数列表）
#      2.4) 模式=所有    → 每参数独立成列，从原最大列+3 开始（保留 2 空列间隔）；
#                          未选参数时默认采用 扫描参数() 的全部结果
#      2.5) 模式=字段及值 → 参数名（去重）写到 原最大列+5 列（前 4 列空白做间隔），从第 1 行起逐行输出；
#                            若 输出对应值=True，则从 原最大列+6 起每个参数独立成列，
#                            列内逐行写出该参数所有去重后的对应值；
#                            参数列表为空 或 全选(=候选集) 时，默认全部参数
# 设计要点：
#   - 不写复杂正则，按空白 split 后建 dict，5 万行 < 200ms
#   - 不重新读 Excel；调用方传入已加载的数据集对象
# ============================================================

